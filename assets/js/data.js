/** data.js - loads and caches the JSON under data/. The only module that fetches
 *  our own files; every renderer goes through it.
 *
 *  Note: served over http(s). Opened straight from file://, fetch() of a local
 *  JSON file is blocked by the browser, so use a static server for local dev.
 */

const cache = new Map();

async function loadJSON(url) {
  if (cache.has(url)) return cache.get(url);
  const p = fetch(url, { cache: 'no-cache' }).then((res) => {
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    return res.json();
  });
  cache.set(url, p);
  return p;
}

/** The generated manifest used by every list page. */
export async function getIndex() {
  return loadJSON('data/index.json');
}

/** One resort's full record. */
export async function getResort(slug) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(String(slug ?? ''))) {
    throw new Error(`bad slug: ${slug}`);
  }
  return loadJSON(`data/resorts/${slug}.json`);
}

/** Generated by tools/fetch-snow.mjs. Missing or stale is a normal state. */
export async function getSnowReports() {
  try {
    return await loadJSON('data/snow-reports.json');
  } catch {
    return { generatedAt: null, reports: {} };
  }
}

/**
 * One resort's snow report, or null. Freshness is the caller's decision, but the
 * rule the UI follows is in `isReportUsable` below so both pages agree.
 */
export async function getSnowReport(slug) {
  const all = await getSnowReports();
  return all?.reports?.[slug] ?? null;
}

/** A report older than this is not shown as numbers, whatever its status says. */
export const REPORT_MAX_AGE_MS = 24 * 60 * 60 * 1000;

/**
 * Numbers are shown only when the fetch succeeded, it is recent, and it actually
 * contains a figure. Everything else - missing, errored, out of season, stale
 * beyond 24 hours - falls back to a link to the resort's official report.
 * Showing a two-day-old base depth as though it were today's is worse than
 * showing nothing.
 */
export function isReportUsable(report, now = Date.now()) {
  if (!report || report.status !== 'ok') return false;
  const fetchedAt = new Date(report.fetchedAt ?? 0).getTime();
  if (!Number.isFinite(fetchedAt) || now - fetchedAt > REPORT_MAX_AGE_MS) return false;
  return ['newSnow24h', 'newSnow48h', 'newSnow7d', 'baseDepth',
    'trailsOpen', 'liftsOpen', 'seasonTotal']
    .some((f) => typeof report[f] === 'number');
}

/** Why a report is not being shown, in words a visitor can act on. */
export function reportUnavailableReason(report, now = Date.now()) {
  if (!report) return 'No automated report for this mountain yet';
  if (report.status === 'closed') return 'No snow report published right now';
  if (report.status === 'error') return 'The automated report could not be fetched';
  const age = now - new Date(report.fetchedAt ?? 0).getTime();
  if (age > REPORT_MAX_AGE_MS) return 'The last automated report is over 24 hours old';
  return 'No figures in the latest report';
}
