#!/usr/bin/env node
/**
 * build-seo.mjs — writes sitemap.xml and robots.txt.
 *
 * These two files are the only places on the whole site where an absolute URL is
 * unavoidable: a sitemap entry must be a full URL by specification, and a
 * robots.txt Sitemap: line must be too. Everything else that needs the host —
 * `<link rel="canonical">`, `og:url` — is written in the browser from
 * `location`, so the rest of the repo stays deployable to any host without a
 * find-and-replace pass. See assets/js/seo.js.
 *
 * Because of that, this script needs the host and will not invent one:
 *
 *   SITE_URL=https://example.netlify.app node tools/build-seo.mjs
 *   node tools/build-seo.mjs --site https://example.netlify.app
 *
 * Run it with no host and it refuses, rather than writing a sitemap full of
 * placeholder URLs that would be committed, deployed, and submitted to a search
 * engine before anybody noticed. A sitemap pointing at the wrong domain is not a
 * degraded sitemap; it is an actively wrong one.
 *
 * Pass --check to verify the committed files match what would be generated,
 * which is what CI would want if this ever runs there.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INDEX_PATH = path.join(ROOT, 'data', 'index.json');

/**
 * Static pages, with a priority and change frequency that reflect what actually
 * changes. `conditions.html` re-fetches a live forecast on every load and is the
 * page most worth recrawling; `about.html` changes when the project does, which
 * is to say rarely.
 */
const STATIC_PAGES = [
  { loc: 'index.html', priority: '1.0', changefreq: 'weekly' },
  { loc: 'conditions.html', priority: '0.9', changefreq: 'daily' },
  { loc: 'map.html', priority: '0.6', changefreq: 'monthly' },
  { loc: 'compare.html', priority: '0.6', changefreq: 'monthly' },
  { loc: 'about.html', priority: '0.4', changefreq: 'yearly' },
];

/**
 * Paths a crawler gains nothing from. `compare.html?r=…` is the important one:
 * it is deep-linkable by design, which means there are 45 choose 2 through 4 of
 * them — a little over 160,000 URLs, all of them assembled from pages that are
 * already indexed separately. Disallowing the parameterised form and listing the
 * bare page keeps the useful one and drops the combinatorial explosion. Prefix
 * matching means `/compare.html?` blocks exactly the parameterised form and
 * leaves `/compare.html` crawlable, with no wildcard syntax involved.
 *
 * Nothing else is listed here. `resort.html` with no or an unknown `?r=` also
 * should not be indexed, but that is a `noindex` meta tag set by the renderer,
 * not a Disallow: expressing it in robots.txt would need the `$` anchor, which
 * only some crawlers understand — and a crawler that reads `/resort.html$`
 * as a plain prefix would drop all 45 detail pages, which are the entire site.
 */
const DISALLOW = [
  '/private/',
  '/compare.html?',
];

const xmlEscape = (s) => String(s)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

function resolveSite() {
  const argIndex = process.argv.indexOf('--site');
  const raw = (argIndex !== -1 ? process.argv[argIndex + 1] : process.env.SITE_URL) ?? '';
  if (!raw) return null;
  let url;
  try {
    url = new URL(raw);
  } catch {
    console.error(`build-seo: "${raw}" is not a URL.`);
    process.exit(1);
  }
  if (!/^https?:$/.test(url.protocol)) {
    console.error(`build-seo: SITE_URL must be http or https, got "${url.protocol}".`);
    process.exit(1);
  }
  // Trailing slash normalised once here so no caller has to think about it.
  return `${url.origin}${url.pathname.replace(/\/+$/, '')}`;
}

function buildSitemap(site, resorts, lastmod) {
  const entries = [
    ...STATIC_PAGES.map((p) => ({ ...p, lastmod })),
    // One entry per resort, at the URL the index links to. `priority` is uniform
    // on purpose: this guide has no opinion about which mountain matters more,
    // and inventing one would be a ranking claim dressed up as metadata.
    ...resorts.map((r) => ({
      loc: `resort.html?r=${encodeURIComponent(r.slug)}`,
      priority: '0.8',
      changefreq: 'monthly',
      lastmod: r.verifiedOn || lastmod,
    })),
  ];

  const body = entries.map((e) => [
    '  <url>',
    `    <loc>${xmlEscape(`${site}/${e.loc}`)}</loc>`,
    e.lastmod ? `    <lastmod>${xmlEscape(e.lastmod)}</lastmod>` : null,
    `    <changefreq>${e.changefreq}</changefreq>`,
    `    <priority>${e.priority}</priority>`,
    '  </url>',
  ].filter(Boolean).join('\n')).join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-seo.mjs. Do not edit by hand; re-run the tool. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;
}

function buildRobots(site) {
  return `# Generated by tools/build-seo.mjs. Do not edit by hand; re-run the tool.
#
# This site fetches other people's snow reports and expects them to honour our
# robots.txt in return, so ours says what it means and nothing more.

User-agent: *
${DISALLOW.map((d) => `Disallow: ${d}`).join('\n')}

Sitemap: ${site}/sitemap.xml
`;
}

async function main() {
  const site = resolveSite();
  if (!site) {
    console.error([
      'build-seo: no site URL.',
      '',
      'sitemap.xml and robots.txt are the only files here that need an absolute',
      'URL, and this script will not guess one — a sitemap pointing at the wrong',
      'domain gets committed, deployed and submitted before anyone notices.',
      '',
      '  SITE_URL=https://your-site.example node tools/build-seo.mjs',
      '  node tools/build-seo.mjs --site https://your-site.example',
      '',
      'See HANDOFF.md.',
    ].join('\n'));
    process.exit(1);
  }

  if (!existsSync(INDEX_PATH)) {
    console.error('build-seo: data/index.json does not exist. Run tools/build-index.mjs first.');
    process.exit(1);
  }

  const index = JSON.parse(await readFile(INDEX_PATH, 'utf8'));
  const resorts = (index.resorts ?? []).filter((r) => r.slug);
  const lastmod = (index.generatedAt ?? new Date().toISOString()).slice(0, 10);

  const files = {
    'sitemap.xml': buildSitemap(site, resorts, lastmod),
    'robots.txt': buildRobots(site),
  };

  if (process.argv.includes('--check')) {
    let ok = true;
    for (const [name, expected] of Object.entries(files)) {
      const p = path.join(ROOT, name);
      const actual = existsSync(p) ? await readFile(p, 'utf8') : null;
      if (actual !== expected) {
        console.error(`build-seo: ${name} is ${actual === null ? 'missing' : 'out of date'}`);
        ok = false;
      }
    }
    if (!ok) process.exit(1);
    console.log(`build-seo: sitemap.xml and robots.txt are up to date for ${site}`);
    return;
  }

  for (const [name, content] of Object.entries(files)) {
    await writeFile(path.join(ROOT, name), content, 'utf8');
  }
  console.log(
    `build-seo: wrote sitemap.xml (${resorts.length + STATIC_PAGES.length} URLs) `
    + `and robots.txt for ${site}`
  );
}

main().catch((e) => {
  console.error('build-seo: unexpected failure\n', e);
  process.exit(1);
});
